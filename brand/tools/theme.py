"""Fill the theme templates from the palette roles.

Run:    python3 brand/tools/theme.py          write every target of brand/palette.json
        python3 brand/tools/theme.py --check  write nothing; exit 1 if a rule is broken
Input:  brand/palette.json (brand colours, roles, targets) and the targets' *.in templates
Output: the targets' output files, e.g. packages/dodo-theme/labwc/themerc (stdlib only)

A template names roles, never colours:
    @@primary@@           #0E6E73
    @@shadow/66@@         #0E262066   (hex alpha appended, for labwc)
    @@primary rgba 0@@    rgba(14,110,115,0)   (for GTK CSS, which has no #RRGGBBAA)

--check fails when a template holds a colour literal, names an unknown role, a role is used
by no template, a role points to a missing brand colour, or an output differs from what the
templates give (someone edited a generated file, or forgot to run this tool).
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PALETTE = ROOT / "brand" / "palette.json"

HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")
TOKEN = re.compile(r"@@([a-z][a-z0-9-]*)(?:/([0-9A-Fa-f]{2})|\s+rgba\s+([0-9.]+))?@@")
# Colour literals a template must not hold. "#taskbar" is a CSS id, not a colour: a hex run
# counts only when no name character follows it.
LITERAL = re.compile(r"#[0-9A-Fa-f]{3,8}(?![0-9A-Za-z_-])|\brgba?\s*\(|\bhsla?\s*\(")


def resolve_roles(palette: dict, variant: str, errors: list) -> dict:
    brand = palette["brand"]
    roles = {}
    for name, role in palette["variants"][variant].items():
        value = role["color"]
        if not HEX.match(value):
            if value not in brand:
                errors.append(f"{variant}/{name}: '{value}' is neither a hex colour nor a brand colour")
                continue
            value = brand[value]
        roles[name] = value.upper()
    return roles


def fill(text: str, roles: dict, where: str, used: set, errors: list) -> str:
    def sub(m):
        name, alpha, rgba = m.group(1), m.group(2), m.group(3)
        if name not in roles:
            errors.append(f"{where}: unknown role '{name}'")
            return m.group(0)
        used.add(name)
        hex6 = roles[name]
        if alpha:
            return hex6 + alpha.upper()
        if rgba:
            r, g, b = (int(hex6[i:i + 2], 16) for i in (1, 3, 5))
            return f"rgba({r},{g},{b},{rgba})"
        return hex6

    for n, line in enumerate(text.splitlines(), 1):
        bare = TOKEN.sub("", line)
        if "@@" in bare:
            errors.append(f"{where}:{n}: malformed token")
        for lit in LITERAL.finditer(bare):
            errors.append(f"{where}:{n}: colour literal '{lit.group(0)}', use a role")
    return TOKEN.sub(sub, text)


def stamp(text: str, template: str, comment: str) -> str:
    """Put a do-not-edit line under the template's first line (the licence header)."""
    note = f"Generated by brand/tools/theme.py from {Path(template).name} and brand/palette.json; do not edit."
    note = f"# {note}" if comment == "#" else f"/* {note} */"
    first, _, rest = text.partition("\n")
    return f"{first}\n{note}\n{rest}"


def main() -> int:
    check = "--check" in sys.argv[1:]
    palette = json.loads(PALETTE.read_text())
    errors = []
    for name, value in palette["brand"].items():
        if not HEX.match(value):
            errors.append(f"brand/{name}: '{value}' is not #RRGGBB")

    roles = {v: resolve_roles(palette, v, errors) for v in palette["variants"]}
    used = {v: set() for v in palette["variants"]}
    stale = []
    for t in palette["targets"]:
        template, output, variant = ROOT / t["template"], ROOT / t["output"], t["variant"]
        text = fill(template.read_text(), roles[variant], t["template"], used[variant], errors)
        text = stamp(text, t["template"], t["comment"])
        if check:
            if not output.exists() or output.read_text() != text:
                stale.append(t["output"])
        elif not errors:
            output.write_text(text)

    for variant, names in roles.items():
        for name in sorted(set(names) - used[variant]):
            errors.append(f"{variant}/{name}: role used by no template; remove it or use it")

    for e in errors:
        print(f"theme: {e}", file=sys.stderr)
    for s in stale:
        print(f"theme: {s} is out of date: run python3 brand/tools/theme.py", file=sys.stderr)
    if errors or stale:
        return 1
    print("theme: ok" if check else f"theme: wrote {len(palette['targets'])} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
